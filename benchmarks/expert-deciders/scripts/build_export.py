def r4(x):
    return None if x is None else round(float(x), 4)


ARM = {"none": "no check (agent alone)", "C": "C: Jev + interview rubric", "D": "D: frontier judge (GPT-6.1 Sol) + rubric + 10 labelled examples",
       "H": "H: hybrid (TF-IDF model on 400 expert labels for handoffs; C for refunds and cards)", "G": "G: Jev + hidden rules written out (ceiling)",
       "gpt5": "GPT-5, no check (incumbent reference)"}
# Rule violations per conversation, conversations with a violation and the paired violation deltas, recomputed from
# results/runs/ by ed_compute_rows.py (the original export copied them from expert_deciders_online.md; same values).
VIOL = {r: (round(x["violations_per_conv"], 3), x["conversations_with_violation"]) for r, x in o.items()}
VIOL_DELTA = {r: tuple(round(x["violations_vs_none"][k], 3) for k in ("delta", "lo", "hi")) for r, x in o.items() if "violations_vs_none" in x}


def row(run):
    x = o[run]
    agent, arm = run.split("_", 1)
    model = {"A": "Qwen/Qwen3.8-27B", "B": "deepseek-ai/DeepSeek-V4.1-Flash", "R": "gpt-5-2025-08-07"}[agent]
    tools = x["by_tool"]
    r = {
        "model": model, "arm": arm, "arm_name": ARM[arm], "run": run,
        "n": x["n"], "scenarios": x["scenarios"], "correct": x["resolved"], "accuracy": r4(x["accuracy"]),
        "ci95": [r4(x["resolved_ci"][1]), r4(x["resolved_ci"][2])],
        "cost_per_correct_cents": r4(x["cost_per_resolved_cents"]),
        "cost_per_conversation_cents": r4(x["cost_per_conv_cents"]),
        "check_cost_per_conversation_cents": r4(x["check_cost_per_conv_cents"]),
        "mean_tokens_per_case": round(x["mean_tokens_traj"], 1),
        "mean_calls_per_case": round(x["mean_calls_traj"], 4),
        "rule_violations_per_conversation": VIOL[run][0],
        "conversations_with_rule_violation": VIOL[run][1],
        "rule_violation_rate": r4(VIOL[run][1] / x["n"]),
        "handoffs": x["handoffs"], "handoffs_per_conversation": r4(x["handoffs"] / x["n"]),
        "unneeded_handoffs": x["bad_handoffs"], "unneeded_handoffs_per_conversation": r4(x["bad_handoffs"] / x["n"]),
        "checks": x["checks"], "blocked": x["blocked"], "blocked_rule_breaking": x["blocked_rule"],
        "blocked_valid": x["blocked"] - x["blocked_rule"], "rule_breaking_let_through": x["allowed_rule"],
        "failures": {"unresolved": x["n"] - x["resolved"], "empty_agent_message_scored_unresolved": x["empty"],
                     "conversations_with_rule_violation": VIOL[run][1], "excluded_infrastructure_error": x["excluded"]},
    }
    if agent in "AB":
        r["inference"] = "commercial inference provider (not named)"
    if "vs_none" in x:
        v = x["vs_none"]
        r["delta_vs_agent_alone"] = r4(v["delta"])
        r["delta_vs_agent_alone_ci95"] = [r4(v["lo"]), r4(v["hi"])]
        r["paired_scenarios"] = v["n"]
        for key, name in (("handoffs_vs_none", "handoffs"), ("bad_handoffs_vs_none", "unneeded_handoffs")):
            d = x[key]
            r[f"{name}_per_conversation_delta_vs_agent_alone"] = r4(d["delta"])
            r[f"{name}_per_conversation_delta_vs_agent_alone_ci95"] = [r4(d["lo"]), r4(d["hi"])]
        vd = VIOL_DELTA[run]
        r["rule_violations_per_conversation_delta_vs_agent_alone"] = vd[0]
        r["rule_violations_per_conversation_delta_vs_agent_alone_ci95"] = [vd[1], vd[2]]
    if "vs_gpt5" in x:
        g = x["vs_gpt5"]
        r["delta_vs_gpt5"] = r4(g["delta"])
        r["delta_vs_gpt5_ci95"] = [r4(g["lo"]), r4(g["hi"])]
    r["by_decision"] = {k: v for k, v in tools.items()}
    return r



"""Analysis of the hard ML-training-ops benchmark runs (mlops_hard/, tasks_mlops_hard.json).

    python mlops_hard_analysis.py   # writes mlops_hard.md

For each harness and config: solves, timeouts, KV-cache load, GPU cost and cost per solve
(attempts.jsonl), and per-task solves from the Harbor job directories. Each config is compared
with the H100 defaults at 24 agents (both repetitions pooled) by a paired bootstrap over tasks.
"""
import collections
import glob
import json
import os
import random

# Benchmark dir (raw Harbor jobs in jobs/, if you have them) and the input rows: $ATTEMPTS_FILE,
# default the published results/runs/attempts.jsonl.
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ATTEMPTS = os.environ.get("ATTEMPTS_FILE") or os.path.join(HERE, "results", "runs", "attempts.jsonl")
TASKS = ["atomic-checkpoint", "corrupt-shard", "ddp-replica-drift", "k8s-unschedulable",
         "memory-leak-oom", "reshard-optimizer", "straggler-diagnosis", "uneven-shard-hang"]
LABEL = {"defaults": "H100, vLLM defaults", "max-out-8k": "H100, server caps output at 8k tokens/call",
         "h200": "H200, vLLM defaults", "no-thinking": "H100, reasoning off",
         "defaults-2x-time": "H100, defaults, 60 min per task instead of 30",
         "max-out-4k": "H100, server caps output at 4k tokens/call", "max-out-16k": "H100, server caps output at 16k tokens/call",
         "moe-a3b": "H100, MoE model (Qwen3.6-35B-A3B)"}


def records():
    out = []
    for line in open(ATTEMPTS):
        r = json.loads(line)
        if (r.get("job_name") or "").startswith("mlops_hard-") and r.get("valid"):
            out.append(r)
    return out


def per_task(job_name, trials=None):
    d = os.path.join(HERE, "jobs", job_name)
    res, timeouts = collections.defaultdict(list), 0
    if not os.path.isdir(d) and trials is not None:
        # Published rows: the per-trial `ok` equals reward.txt >= 1 for every ML-ops run (checked
        # against the raw jobs before publishing); raw jobs/ is not published.
        for t in trials:
            res[t["task"]].append(int(t["ok"]))
            timeouts += t.get("exc") == "AgentTimeoutError"
        return res, timeouts
    for t in glob.glob(os.path.join(d, "*", "result.json")):
        trial = os.path.dirname(t)
        r = json.load(open(t))
        rw = os.path.join(trial, "verifier", "reward.txt")
        res[os.path.basename(trial).split("__")[0]].append(int(float(open(rw).read().strip())) if os.path.exists(rw) else 0)
        timeouts += (r.get("exception_info") or {}).get("exception_type") == "AgentTimeoutError"
    return res, timeouts


def boot(a, b, n=10000, seed=0):
    """Paired bootstrap over tasks of the difference in mean solve rate (b - a)."""
    rng = random.Random(seed)
    rate = lambda d, t: sum(d[t]) / len(d[t])  # noqa: E731
    diffs = sorted(sum(rate(b, t) - rate(a, t) for t in s) / len(s)
                   for s in ([rng.choice(TASKS) for _ in TASKS] for _ in range(n)))
    point = sum(rate(b, t) - rate(a, t) for t in TASKS) / len(TASKS)
    return point, diffs[int(0.025 * n)], diffs[int(0.975 * n)]


def main():
    recs = records()
    rows, tasks = [], {}
    for r in recs:
        res, to = per_task(r["job_name"], r["trials"])
        key = (r["harness"], r["config"], r["concurrency"])
        merged = tasks.setdefault(key, collections.defaultdict(list))
        for t, v in res.items():
            merged[t] += v
        v = r.get("vllm") or {}
        rows.append((r, to, v))
    lines = ["# Hard ML-training-ops benchmark: how serving setup moves outcomes", "",
             "Qwen3.8-27B, 8 tasks x 3 attempts per run, 30 min of agent time per trial unless stated.",
             "Generated by `mlops_hard_analysis.py` from `attempts.jsonl` and the Harbor job directories.", "",
             "## All runs", "",
             "| harness | setup | agents at once | rep | solved | timeouts | KV mean / peak | GPU $ | $ per solve (GPU + sandbox est.) |",
             "|---|---|---|---|---|---|---|---|---|"]
    for r, to, v in sorted(rows, key=lambda x: (x[0]["harness"], x[0]["config"] != "defaults", x[0]["config"], -x[0]["concurrency"], x[0]["rep"])):
        lines.append(f"| {r['harness']} | {LABEL.get(r['config'], r['config'])} | {r['concurrency']} | {r['rep']} | "
                     f"{r['solved']} / {r['attempted']} | {to} | {v.get('kv_usage_mean', 0):.0%} / {v.get('kv_usage_max', 0):.0%} | "
                     f"{r['cost']:.2f} | {r['total_cost_per_solved']:.3f} |")
    lines += ["", "## Each setup vs H100 defaults at 24 agents (paired bootstrap over the 8 tasks, 95% CI)", "",
              "Defaults at 24 agents pools both repetitions (6 attempts per task).", "",
              "| harness | setup | solve rate | baseline | difference (points) | 95% CI |", "|---|---|---|---|---|---|"]
    for h in ("terminus-2", "mini-swe-agent"):
        base = tasks.get((h, "defaults", 24))
        if not base:
            continue
        br = sum(map(sum, base.values())) / sum(map(len, base.values()))
        for (hh, cfg, c), d in sorted(tasks.items()):
            if hh != h or (cfg, c) == ("defaults", 24) or not all(t in d for t in TASKS):
                continue
            p, lo, hi = boot(base, d)
            sr = sum(map(sum, d.values())) / sum(map(len, d.values()))
            name = LABEL.get(cfg, cfg) + ("" if c == 24 else f", {c} agents")
            lines.append(f"| {h} | {name} | {sr:.0%} | {br:.0%} | {100 * p:+.0f} | [{100 * lo:+.0f}, {100 * hi:+.0f}] |")
    lines += ["", "## Per task (solved / attempts)", ""]
    keys = sorted(tasks, key=lambda k: (k[0], k[1] != "defaults", k[1], -k[2]))
    lines.append("| task | " + " | ".join(f"{h[:4]} {c}@{n}" for h, c, n in keys) + " |")
    lines.append("|---|" + "---|" * len(keys))
    for t in TASKS:
        lines.append(f"| {t} | " + " | ".join(f"{sum(tasks[k].get(t, []))}/{len(tasks[k].get(t, []))}" for k in keys) + " |")
    open(os.path.join(HERE, "mlops_hard.md"), "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()

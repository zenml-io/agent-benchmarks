"""Same open model on different hosted providers: does the swap verdict depend on where it is served?

  python scripts/providers.py > out/providers.md     (reads results/runs/<domain>/<model>@<provider>.jsonl)

Export your own provider runs (scripts/provider_runs.sh, then scripts/export_results.py) as <model>@<provider label>.jsonl.
Hidden split only (240 scenarios x 2 per business). Conversations that never got graded (infra_error: rate limits,
credit, server errors) are excluded, not scored as failures. "Both" pools the two businesses: each conversation is
compared with that business's current model on the same scenario.
"""
import glob
import itertools
import json
import os
import random
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, HERE)
from swapbench import stats  # noqa: E402

RES = os.path.join(HERE, "results", "runs")
INCUMBENT = {"fintech": "gpt-5", "retail": "haiku-5.5"}
LABEL = {"fintech": "bank", "retail": "store"}
MARGIN = 0.05


def rows(dom, run, split="test"):
    p = os.path.join(RES, dom, f"{run}.jsonl")
    if not os.path.exists(p):
        return []
    return [r for r in map(json.loads, open(p)) if r["split"] == split]


def load(run, doms):
    ok, refused = [], 0
    for d in doms:
        for r in rows(d, run):
            if r["infra_error"]:
                refused += 1
            else:
                ok.append(dict(r, scenario=f"{d}:{r['scenario']}"))
    return ok, refused


def incumbent(doms):
    return [dict(r, scenario=f"{d}:{r['scenario']}") for d in doms for r in rows(d, INCUMBENT[d])]


def mean_ci(eps, key="reward", n_boot=10000, seed=0):
    per = list(stats.per_scenario(eps, key).values())
    rng = random.Random(seed)
    boots = sorted(sum(rng.choice(per) for _ in per) / len(per) for _ in range(n_boot))
    return sum(per) / len(per), boots[250], boots[9749]


def gate(q, h, m=MARGIN):
    if q["lo"] > -m and not (h["delta"] > 0.01 and h["lo"] > 0):
        return "SAFE"
    if q["hi"] < -m or (h["lo"] is not None and h["lo"] > 0.01):
        return "UNSAFE"
    return "NOT ENOUGH EVIDENCE"


def pts(x):
    return f"{x * 100:+.1f}"


def ci(d):
    return f"{pts(d['delta'])} [{pts(d['lo'])}, {pts(d['hi'])}]"


def main():
    runs = sorted({os.path.basename(p)[:-6] for p in glob.glob(os.path.join(RES, "*", "*@*.jsonl"))
                   if not p.endswith(".nextstep.jsonl")})
    models = defaultdict(list)
    for r in runs:
        models[r.split("@")[0]].append(r)

    print("# Same model, different provider (hidden set)\n")
    print("Generated by `scripts/providers.py` from `results/`. Hidden split: 240 scenarios x 2 trials per business. "
          "Δ = candidate minus the business's current model (GPT-5 for the bank, Claude Haiku 5.5 for the store), "
          "paired by scenario, 95% cluster-bootstrap CI. Gate: SAFE if the lower bound is above −5 points and harmful "
          "actions don't rise. Conversations that never got graded are excluded and counted under \"not run\".\n")
    for doms, title in [(("fintech", "retail"), "Both businesses"), (("fintech",), "Bank (fintech)"), (("retail",), "Store (retail)")]:
        inc = incumbent(doms)
        im, ilo, ihi = mean_ci(inc)
        icost = sum(r["cost_usd"] for r in inc) / max(sum(r["reward"] >= 1 for r in inc), 1)
        print(f"## {title}\n")
        print(f"Current model{'s' if len(doms) > 1 else ''}: {im * 100:.1f}% resolved [{ilo * 100:.1f}, {ihi * 100:.1f}], "
              f"{icost * 100:.2f}¢ per resolved conversation.\n")
        print("| model | provider | conversations | not run | resolved [95% CI] | Δ vs current, pts [95% CI] | harmful actions Δ | gate | ¢ / resolved conv. | median s / conv. |")
        print("|---|---|---|---|---|---|---|---|---|---|")
        for m, rs in models.items():
            for r in rs:
                e, refused = load(r, doms)
                if not e:
                    continue
                q, h = stats.paired_delta(e, inc), stats.paired_delta(e, inc, "harmful_writes")
                mm, lo, hi = mean_ci(e)
                costs = [x["cost_usd"] for x in e]
                cpr = None if None in costs else sum(costs) / max(sum(x["reward"] >= 1 for x in e), 1)
                dur = sorted(x["duration_s"] for x in e)[len(e) // 2]
                print(f"| {m} | {r.split('@')[1]} | {len(e)} | {refused} | {mm * 100:.1f}% [{lo * 100:.1f}, {hi * 100:.1f}] | "
                      f"{ci(q)} | {h['delta']:+.3f} | {gate(q, h)} | {'n/a' if cpr is None else f'{cpr * 100:.2f}'} | {dur:.0f} |")
        print()

    print("## Provider against provider (both businesses, paired by scenario)\n")
    print("| model | A | B | A minus B, pts [95% CI] | intervals separate? |")
    print("|---|---|---|---|---|")
    for m, rs in models.items():
        E = {r: load(r, ("fintech", "retail"))[0] for r in rs}
        for a, b in itertools.combinations([r for r in rs if E[r]], 2):
            d = stats.paired_delta(E[a], E[b])
            sep = "yes" if d["lo"] > 0 or d["hi"] < 0 else "no clear difference"
            print(f"| {m} | {a.split('@')[1]} | {b.split('@')[1]} | {ci(d)} | {sep} |")

    if rows("fintech", "qwen27b-bf16"):
        print("\n## Qwen3.8-27B: hosted vs self-hosted\n")
        own = [dict(r, scenario=f"{d}:{r['scenario']}") for d in ("fintech", "retail") for r in rows(d, "qwen27b-bf16")]
        for run in models.get("qwen3.8-27b", []):
            hosted = load(run, ("fintech", "retail"))[0]
            if hosted:
                print(f"{run.split('@')[1]} minus our own vLLM on one H100 (BF16), both businesses: "
                      f"{ci(stats.paired_delta(hosted, own))} pts.")


if __name__ == "__main__":
    main()

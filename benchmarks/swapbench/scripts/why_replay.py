"""Why next-step agreement misses bad swaps: where candidate conversations go wrong, and whether the recorded incumbent
conversation ever reached that point.

  python scripts/why_replay.py <raw-root> > experiments/why_replay.md      (any python; reads raw tau2 results)

For each swap that next-step agreement wrongly called SAFE (fintech: GPT-6 Luna, Qwen BF16, Qwen FP8), on the hidden
set, trial by trial against the incumbent (GPT-5) on the same scenario and trial:
- failure kind: which gold write was missed, or which write was not in the gold (by tool), and handoffs;
- first divergence: the first tool call (name + arguments) where the two conversations differ;
- off-record: whether the candidate's first wrong or missing write happens after its tool calls have already left the
  incumbent's sequence. A next-step replay only ever asks the candidate about states on the incumbent's path, so such
  errors are invisible to it.
"""
import json
import os
import sys
from collections import Counter, defaultdict

RUNS = {"GPT-6 Luna": "fgt/openai_responses_gpt-6-luna", "Qwen3.8-27B BF16": "fvc/open/qwen27b",
        "Qwen3.8-27B FP8": "fvc/comb/qwen27b-fp8"}
INCUMBENT = "fgt/gpt-5-2025-08-07"
READ_ONLY = {"verify_identity", "get_account", "get_transactions", "get_customer", "lookup", "get_card"}


def sims(root, run):
    d = json.load(open(os.path.join(root, run, "test", "results.json")))
    return {(s["task_id"], s["trial"]): s for s in d["simulations"] if s.get("reward_info")}


def calls(s):
    out = []
    for m in s["messages"]:
        if m["role"] == "assistant":
            for t in m.get("tool_calls") or []:
                out.append((t["name"], json.dumps(t["arguments"], sort_keys=True)))
    return out


def is_write(name):
    return name not in READ_ONLY and not name.startswith("get_")


def gold(s):
    return [(a["action"]["name"], json.dumps(a["action"]["arguments"], sort_keys=True))
            for a in s["reward_info"].get("action_checks") or []]


def classify(s):
    """Return (kind, index of the first bad call or None)."""
    g = gold(s)
    c = calls(s)
    writes = [(i, x) for i, x in enumerate(c) if is_write(x[0])]
    gset = Counter(g)
    for i, w in writes:
        if gset[w] > 0:
            gset[w] -= 1
            continue
        same_tool = [x for x in g if x[0] == w[0]]
        if same_tool:
            return f"{w[0]}: wrong arguments", i
        if w[0] in ("escalate_to_human", "transfer_to_human_agents"):
            return "handed off when the gold had no handoff", i
        return f"{w[0]}: action not in the gold", i
    missing = [x for x in g if x not in [w for _, w in writes]]
    if missing:
        return f"{missing[0][0]}: required action never taken", len(c)
    return "end state differs (other)", None


def main():
    root = sys.argv[1]
    inc = sims(root, INCUMBENT)
    print("# Why next-step agreement misses bad swaps (fintech, hidden set)\n")
    print("Generated by `scripts/why_replay.py` from raw tau2 transcripts. Candidate vs GPT-5 on the same scenario and "
          "trial. 'Off the recorded path' means the candidate's first wrong or missing action came after its tool calls "
          "had already differed from GPT-5's: a next-step replay, which only asks the candidate about GPT-5's recorded "
          "states, never sees that situation.\n")
    allkinds = Counter()
    for name, run in RUNS.items():
        cand = sims(root, run)
        rows = []
        for k, cs in cand.items():
            if k not in inc:
                continue
            ci, cc = inc[k], cs
            if not (ci["reward_info"]["reward"] >= 1 and cc["reward_info"]["reward"] < 1):
                continue
            a, b = calls(ci), calls(cc)
            div = next((i for i in range(min(len(a), len(b))) if a[i] != b[i]), min(len(a), len(b)) if len(a) != len(b) else None)
            kind, bad = classify(cc)
            off = div is not None and bad is not None and bad > div
            at_div = div is not None and bad is not None and bad == div
            n_turns = sum(m["role"] == "assistant" for m in cc["messages"])
            rows.append(dict(k=k, kind=kind, div=div, bad=bad, off=off, at_div=at_div, turns=n_turns))
        n = len(rows)
        print(f"## {name}\n")
        print(f"Conversations GPT-5 resolved and {name} did not: **{n}**.\n")
        if not n:
            continue
        print(f"- First wrong or missing action **after the conversation had already left GPT-5's path**: "
              f"{sum(r['off'] for r in rows)} of {n} ({sum(r['off'] for r in rows) / n:.0%}).")
        print(f"- First wrong action **at the first point of divergence** (a next-step replay could see it): "
              f"{sum(r['at_div'] for r in rows)} of {n} ({sum(r['at_div'] for r in rows) / n:.0%}).")
        divs = [r["div"] for r in rows if r["div"] is not None]
        if divs:
            print(f"- Median tool call where the paths first differ: {sorted(divs)[len(divs) // 2] + 1}; "
                  f"median conversation length: {sorted(r['turns'] for r in rows)[n // 2]} agent turns.")
        kinds = Counter(r["kind"] for r in rows)
        allkinds.update(kinds)
        print("\n| what went wrong | conversations |\n|---|---|")
        for kd, c in kinds.most_common():
            print(f"| {kd} | {c} |")
        print()
    print("## All three swaps together: the decision points that fail\n")
    print("| what went wrong | conversations |\n|---|---|")
    for kd, c in allkinds.most_common():
        print(f"| {kd} | {c} |")


if __name__ == "__main__":
    main()

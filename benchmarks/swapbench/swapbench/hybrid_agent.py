"""Decomposed agents: a cheap model for most of the work, a frontier model only where it matters.

Registered by `swapbench.fintech.run` when SWAPBENCH_HYBRID=1:
- `jev_route`: the cheap model (--agent-llm) runs the conversation. When it proposes a state-changing action and Jev
  says the policy does not allow it, that turn is regenerated by the frontier model (SWAPBENCH_FALLBACK_LLM) instead.
- `split`: the cheap model makes every tool decision; whenever it would reply to the customer in words, the frontier
  model writes that turn instead (it may also choose a tool call). "Cheap decisions, frontier words."

Every model call, including discarded ones, is logged with its model and token usage to SWAPBENCH_CALL_LOG, so the
real cost of a run includes the calls a trajectory no longer shows.
"""
import json
import os

from tau2.agent.llm_agent import LLMAgent
from tau2.utils.llm_utils import generate

from swapbench.jev_agent import MIN_CONF, RULES, THRESHOLD, LOG as JEV_LOG, _render, ask_jev

FALLBACK = os.environ.get("SWAPBENCH_FALLBACK_LLM", "gpt-5-2025-08-07")
CALL_LOG = os.environ.get("SWAPBENCH_CALL_LOG")


def _log(model, msg, role):
    if CALL_LOG:
        with open(CALL_LOG, "a") as f:
            f.write(json.dumps(dict(model=model, role=role, usage=getattr(msg, "usage", None),
                                    tool=bool(msg.tool_calls))) + "\n")


class _Base(LLMAgent):
    def _gen(self, state, model, llm_args, role):
        msg = generate(model=model, tools=self.tools, messages=state.system_messages + state.messages,
                       call_name="agent_response", **(llm_args or {}))
        _log(model, msg, role)
        return msg

    def _first(self, message, state):
        from tau2.data_model.message import MultiToolMessage
        if isinstance(message, MultiToolMessage):
            state.messages.extend(message.tool_messages)
        else:
            state.messages.append(message)
        return self._gen(state, self.llm, self.llm_args, "cheap")


class JevRouteAgent(_Base):
    def _generate_next_message(self, message, state):
        msg = self._first(message, state)
        writes = [t for t in (msg.tool_calls or []) if t.name in RULES]
        if not writes:
            return msg
        t = writes[0]
        d = ask_jev(_render(state.messages, t), t.name)
        risky = d.get("choice") == "not_allowed" and (d.get("confidence") or 0) >= THRESHOLD.get(t.name, MIN_CONF)
        if JEV_LOG:
            with open(JEV_LOG, "a") as f:
                f.write(json.dumps(dict(tool=t.name, arguments=t.arguments, routed=risky, **d)) + "\n")
        if not risky:
            return msg
        return self._gen(state, FALLBACK, {}, "frontier")


class SplitAgent(_Base):
    def _generate_next_message(self, message, state):
        msg = self._first(message, state)
        if msg.tool_calls:
            return msg
        return self._gen(state, FALLBACK, {}, "frontier")


def register():
    from tau2.registry import registry

    def mk(cls):
        return lambda tools, domain_policy, **kw: cls(tools=tools, domain_policy=domain_policy, llm=kw.get("llm"),
                                                      llm_args=kw.get("llm_args"))
    registry.register_agent_factory(mk(JevRouteAgent), "jev_route")
    registry.register_agent_factory(mk(SplitAgent), "split")
    registry.register_agent_factory(mk(OutcomeGateAgent), "outcome_gate")
    registry.register_agent_factory(mk(DeciderGateAgent), "decider_gate")


class OutcomeGateAgent(_Base):
    """Like `jev_gate`, but the handoff check is a small model trained on past outcomes (no rule text):
    scripts/train_outcome_decider.py, loaded from SWAPBENCH_DECIDER. Blocks `escalate_to_human` when the predicted
    chance of an unresolved conversation is above the trained threshold; the model then tries again (max 2 blocks)."""
    _dec = None

    def _generate_next_message(self, message, state):
        import pickle
        from tau2.data_model.message import ToolMessage
        if OutcomeGateAgent._dec is None:
            OutcomeGateAgent._dec = pickle.load(open(os.environ["SWAPBENCH_DECIDER"], "rb"))
        d = OutcomeGateAgent._dec
        msg = self._first(message, state)
        for _ in range(2):
            t = next((c for c in (msg.tool_calls or []) if c.name == "escalate_to_human"), None)
            if t is None:
                return msg
            text = _render(state.messages, t).split("\n\nPROPOSED ACTION:")[0][-3000:]
            p = float(d["clf"].predict_proba(d["vec"].transform([text]))[0, 1])
            blocked = p > d["threshold"]
            if JEV_LOG:
                with open(JEV_LOG, "a") as f:
                    f.write(json.dumps(dict(tool=t.name, arguments=t.arguments, p_bad=round(p, 3), blocked=blocked)) + "\n")
            if not blocked:
                return msg
            state.messages.append(msg)
            state.messages.extend(ToolMessage(id=c.id, role="tool", requestor="assistant", error=True,
                                              content="Blocked by the automated check: handing off now usually ends "
                                                      "badly in cases like this. Help the customer directly or explain "
                                                      "the policy instead." if c is t else "Not executed.")
                                  for c in msg.tool_calls)
            msg = self._gen(state, self.llm, self.llm_args, "cheap")
        return msg


class DeciderGateAgent(_Base):
    """Expert-deciders benchmark: checks every handoff, refund and card freeze with one arm's decider and blocks it
    when p(should not happen) > 0.5 (the model sees a generic refusal and tries again, at most twice).
    SWAPBENCH_ED_ARM: B (Jev, written policy), C (Jev + interview rubric), D (frontier judge + rubric + examples),
    E (small model, SWAPBENCH_ED_MODEL pickle), G (Jev + hidden rules), H (hybrid: word-count model for handoffs, C for
    refunds and cards). SWAPBENCH_ED_DIR holds rubric.json,
    judge_examples.json and the pickle. Decisions are logged to SWAPBENCH_JEV_LOG with the hidden-rule truth."""
    _ctx = None

    @classmethod
    def ctx(cls):
        if cls._ctx is None:
            import pickle
            from swapbench.hidden_rules import rules_text
            d = os.environ["SWAPBENCH_ED_DIR"]
            arm = os.environ["SWAPBENCH_ED_ARM"]
            from scripts import ed_arms  # noqa: F401  (needs the swapbench dir on PYTHONPATH)
            c = dict(arm=arm, ed=ed_arms, rubric=json.load(open(os.path.join(d, "rubric.json"))) if arm in "CD" else None,
                     db=json.load(open(os.path.join(os.environ["SWAPBENCH_FINTECH_DIR"], "db.json"))), emb_cache={})
            if arm == "D":
                c["examples"] = {p: [(s, y) for s, y in v] for p, v in json.load(open(os.path.join(d, "judge_examples.json"))).items()}
            if arm == "E":
                c["models"] = pickle.load(open(os.environ["SWAPBENCH_ED_MODEL"], "rb"))
            if arm == "H":  # hybrid: word-count model for handoffs, Jev + interview rubric (C) for refunds and cards
                c["handoff_model"] = pickle.load(open(os.path.join(d, "online_T400_handoff.pkl"), "rb"))
                c["rubric"] = json.load(open(os.path.join(d, "rubric.json")))
            W = ed_arms.WRITTEN
            c["rules"] = {"B": W, "H": {p: W[p] + "\nAlso these rules from the bank's senior support lead:\n" + c["rubric"].get(p, "") for p in W} if arm == "H" else None,
                          "C": {p: W[p] + "\nAlso these rules from the bank's senior support lead:\n" + (c["rubric"] or {}).get(p, "") for p in W},
                          "G": {p: W[p] + "\nAlso these working rules:\n" + rules_text(p) for p in W}}.get(arm)
            cls._ctx = c
        return cls._ctx

    def _score(self, messages, t, point):
        c = self.ctx()
        from scripts.ed_build_steps import render
        from swapbench.hidden_rules import _norm
        dicts = [dict(role=r, content=x, tool_calls=tc) for r, x, tc in _norm(messages)]
        step = dict(state=render(dicts)[-12000:], tool=t.name, arguments=t.arguments, point=point)
        ed = c["ed"]
        if c["arm"] == "H" and point == "handoff":
            m = c["handoff_model"]
            return float(m["clf"].predict_proba(m["vec"].transform([ed.state_text(step)]))[0, 1]), dicts
        if c["arm"] in "BCGH":
            r = ed.jev(ed.state_text(step), ed.QUESTION[point], "Yes: the action follows these rules.\n" + c["rules"][point],
                       "No: the action breaks one of these rules.\n" + c["rules"][point])
            return r.get("p"), dicts
        if c["arm"] == "D":
            return ed.judge_one(dict(step, id="live"), c["rubric"], c["examples"]).get("p"), dicts
        X = ed.embed([ed.state_text(step)], c["emb_cache"])
        return float(c["models"][point].predict_proba(X)[0, 1]), dicts

    def _generate_next_message(self, message, state):
        from tau2.data_model.message import ToolMessage
        from swapbench.hidden_rules import POINT, violations
        msg = self._first(message, state)
        for _ in range(2):
            t = next((x for x in (msg.tool_calls or []) if x.name in POINT), None)
            if t is None:
                return msg
            p, dicts = self._score(state.messages, t, POINT[t.name])
            blocked = p is not None and p > 0.5
            if JEV_LOG:
                with open(JEV_LOG, "a") as f:
                    f.write(json.dumps(dict(tool=t.name, arguments=t.arguments, p=p, blocked=blocked,
                                            truth=violations(dicts, t.name, t.arguments, self.ctx()["db"]))) + "\n")
            if not blocked:
                return msg
            state.messages.append(msg)
            state.messages.extend(ToolMessage(id=c.id, role="tool", requestor="assistant", error=True,
                                              content="Blocked by the bank's automated check: this action should not go "
                                                      "ahead here. Explain to the customer or take a different step."
                                              if c is t else "Not executed.")
                                  for c in msg.tool_calls)
            msg = self._gen(state, self.llm, self.llm_args, "cheap")
        return msg
